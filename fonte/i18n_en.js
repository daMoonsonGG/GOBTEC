function traducirEn(txt) {
  const orixe = txt.replace(/\s+/g, ' ').trim();
  if (!orixe) return txt;
  if (Object.prototype.hasOwnProperty.call(DIC_EN, orixe)) return txt.replace(orixe === txt ? txt : txt.trim(), DIC_EN[orixe]);
  for (const [re, f] of REGRAS_EN) {
    const m = orixe.match(re);
    if (m) return f(m);
  }
  if (orixe.includes(' · ')) return orixe.split(' · ').map(traducirEn).join(' · ');
  return fragmentosEn(orixe);
}

